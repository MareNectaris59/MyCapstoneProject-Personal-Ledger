-- =============================================================================
--  V4：给用户表增加令牌版本号
--
--  为什么要这一列：
--    改密码后，此前签发的 accessToken 在过期前依然有效 —— 无状态 JWT 的固有问题。
--    攻击者若已拿到令牌，用户改密并不能把对方踢下线。
--
--  做法：令牌里带 token_version 声明，过滤器每次校验时与库里比对。
--    改密时自增该列，所有旧令牌的声明值立刻落后，下一次请求即被拒绝。
--
--  代价：每个带令牌的请求多一次按主键查询。对单用户记账应用可以接受，
--    换来的是"改密/被踢下线"这类安全语义真正成立。
-- =============================================================================

ALTER TABLE sys_user
    ADD COLUMN token_version INT NOT NULL DEFAULT 0
        COMMENT '令牌版本号：修改密码时自增，使此前签发的所有令牌立即失效';