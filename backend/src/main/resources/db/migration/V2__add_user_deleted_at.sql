-- ============================================================
-- V2：为用户表增加「注销时间」字段
--
-- 背景：
--   新增账号注销功能（DELETE /api/v1/users/me）。注销时需要记录
--   操作时间，便于审计与后续的数据清理策略。
--
-- 注意：
--   sys_user.deleted 是 MyBatis-Plus 的逻辑删除标记（0/1），它表达
--   "这条记录是否有效"；而 deleted_at 表达"什么时候注销的"。两者
--   语义不同，都需要保留 —— 只有 deleted 无法回答"何时注销"，
--   而这个时间点对数据保留策略是必需的。
--
--   V1 是 Flyway 基线（由现有库结构导出，已被校验和锁定），因此列变更
--   必须作为新的迁移版本追加，不能修改 V1。
-- ============================================================

ALTER TABLE `sys_user`
  ADD COLUMN `deleted_at` DATETIME(3) NULL DEFAULT NULL
  COMMENT '注销时间；NULL 表示未注销' AFTER `deleted`;
